# gen.py <dir> [--old <backup of the pre-integration top level>]
# controllers.sv equivalence test generator (CTL-2026-10-25, wave 2). Reads <dir>/cfg.py and writes:
#   new_in.sv          the LIVE top level's input block (always regenerated)
#   old_in.sv          the pre-integration input block, verbatim            (only with --old)
#   oldm_in.sv         old block + every intended-difference patch (model)  (only with --old)
#   old_<C>_in.sv      old block + the patch of class C only (attribution)   (only with --old)
#   tb_cfg.svh         instances / widths / stimulus tables for tb_integ.sv
# cfg.py: CLK, OLD_RANGES / NEW_RANGES [(start_re, end_re)], DROP [re], DECLS, OUT [expr], OUT_W, CLASSES {name: [(old, new)]},
#         CODES [ps2 codes], THR [stick thresholds], XIN_NOTE.
import os, re, sys
d = sys.argv[1]
old = sys.argv[sys.argv.index('--old') + 1] if '--old' in sys.argv else None
cfg = {}
exec(open(os.path.join(d, 'cfg.py')).read(), cfg)
new_top = os.path.normpath(os.path.join(d, cfg['NEW_TOP']))

def extract(path, ranges):
    lines = open(path, errors='replace').read().splitlines()
    out, cur = [], 0
    for s_re, e_re in ranges:
        s = next(i for i in range(cur, len(lines)) if re.search(s_re, lines[i]))
        e = next(i for i in range(s, len(lines)) if re.search(e_re, lines[i]))
        out.append('// ---- %s lines %d-%d' % (os.path.basename(path), s + 1, e + 1))
        out += [l for l in lines[s:e + 1] if not any(re.search(x, l) for x in cfg.get('DROP', []))]
        cur = e + 1
    return '\n'.join(out) + '\n'

HDR = '''// GENERATED by gen.py (controllers.sv equivalence test, CTL-2026-10-25) from {src}: do not edit
module {name}
(
    input          clk,
    input   [15:0] joystick_0, joystick_1,
    input   [15:0] joystick_analog_0, joystick_analog_1, joystick_r_analog_0, joystick_r_analog_1,
    input   [10:0] ps2_key,
    input          pause_cpu,
    input  [127:0] status,
    input          vblank,
    input   [63:0] xin,
    output [{ow}:0] o
);
wire {clk} = clk;
{decls}
'''

def module(name, src, body):
    return (HDR.format(name=name, src=src, ow=cfg['OUT_W'] - 1, clk=cfg['CLK'], decls=cfg.get('DECLS', '')) + body +
            '\nassign o = {%s};\nendmodule\n' % ', '.join(cfg['OUT']))

def patch(body, pairs):
    for a, b in pairs:
        n = body.count(a)
        assert n >= 1, 'patch not found: %r' % a          # no silent no-op patches
        body = body.replace(a, b)
    return body

open(os.path.join(d, 'new_in.sv'), 'w').write(module('new_in', os.path.basename(new_top), extract(new_top, cfg['NEW_RANGES'])))
classes = cfg.get('CLASSES', {})
if old:
    ob = extract(old, cfg['OLD_RANGES'])
    src = os.path.basename(old)
    open(os.path.join(d, 'old_in.sv'), 'w').write(module('old_in', src, ob))
    allp = [p for c in classes for p in classes[c]]
    open(os.path.join(d, 'oldm_in.sv'), 'w').write(module('oldm_in', src + ' + all intended-difference patches',
                                                          patch(ob, allp) if allp else ob))
    for c in classes:
        open(os.path.join(d, 'old_%s_in.sv' % c), 'w').write(module('old_%s_in' % c, src + ' + patch ' + c, patch(ob, classes[c])))
codes = cfg.get('CODES', []) + [0x75, 0x72, 0x6B, 0x74, 0x14, 0x11, 0x16, 0x1E, 0x2E, 0x36, 0x46, 0x2C, 0x4D, 0x12, 0x29, 0x1C]
codes = sorted(set(codes))
thr = cfg.get('THR', [64])
with open(os.path.join(d, 'tb_cfg.svh'), 'w') as f:
    f.write('// GENERATED by gen.py: do not edit\n')
    f.write('localparam int OW = %d;\nlocalparam int NCLS = %d;\n' % (cfg['OUT_W'], max(1, len(classes))))
    f.write('localparam int NCODES = %d;\nreg [7:0] codes[NCODES] = \'{%s};\n' % (len(codes), ', '.join("8'h%02X" % c for c in codes)))
    f.write('localparam int NTHR = %d;\nint thr[NTHR] = \'{%s};\n' % (len(thr), ', '.join(str(t) for t in thr)))
    f.write('string cls_name[NCLS] = \'{%s};\n' % (', '.join('"%s"' % c for c in classes) if classes else '"none"'))
    eo = cfg.get('EXACT_OK', [])
    f.write('bit exact_ok[NCLS] = \'{%s};\n' % (', '.join("1'b%d" % (c in eo) for c in classes) if classes else "1'b0"))
    f.write('wire [OW-1:0] o_dut, o_raw, o_all;\nwire [OW-1:0] o_cls[NCLS];\n')
    f.write('new_in  dut(.*, .o(o_dut));\nold_in  raw(.*, .o(o_raw));\noldm_in mdl(.*, .o(o_all));\n')
    if classes:
        for i, c in enumerate(classes):
            f.write('old_%s_in m_%s(.*, .o(o_cls[%d]));\n' % (c, c, i))
    else:
        f.write('assign o_cls[0] = o_raw;\n')
print('gen.py: new_in.sv%s, %d classes, OUT_W %d' % (' + old files' if old else '', len(classes), cfg['OUT_W']))
